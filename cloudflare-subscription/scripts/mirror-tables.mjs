// Builds the cloud copies of the app tables from lib/core/db/tables.dart:
//   node scripts/mirror-tables.mjs            → writes src/mirror_tables.js
//   node scripts/mirror-tables.mjs --sql      → prints CREATE TABLE + backfill
// Run it after an app schema change and add the SQL as a new migration
// (for a new column: ALTER TABLE ... ADD COLUMN instead of CREATE TABLE).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dart = readFileSync(join(here, '../../lib/core/db/tables.dart'), 'utf8');

// Tables that stay on the phone (lib/core/sync/sync_schema.dart).
const LOCAL_ONLY = new Set(['app_meta', 'backup_logs']);
const SQL_TYPES = {
  TextColumn: 'TEXT',
  IntColumn: 'INTEGER',
  BoolColumn: 'INTEGER',
  RealColumn: 'REAL',
};

const snake = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();

const tables = [];
const classRe = /class (\w+) extends Table( with Timestamps)? \{([\s\S]*?)\n\}/g;
for (const [, className, timestamps, body] of dart.matchAll(classRe)) {
  const name = snake(className);
  if (LOCAL_ONLY.has(name)) continue;
  const columns = [];
  for (const [, type, column] of body.matchAll(/(\w+Column) get (\w+) =>/g)) {
    if (!SQL_TYPES[type]) throw new Error(`Unknown column type ${type}`);
    columns.push([snake(column), SQL_TYPES[type]]);
  }
  if (timestamps) columns.push(['created_at', 'INTEGER'], ['updated_at', 'INTEGER']);
  if (!columns.some(([c]) => c === 'id')) throw new Error(`${name} has no id`);
  tables.push({ name, columns });
}

if (process.argv.includes('--sql')) {
  const out = [];
  for (const { name, columns } of tables) {
    const defs = columns
      .filter(([c]) => c !== 'id')
      .map(([c, t]) => `  ${c} ${t},`)
      .join('\n');
    out.push(`CREATE TABLE IF NOT EXISTS ${name} (
  account_id TEXT NOT NULL,
  id TEXT NOT NULL,
${defs}
  PRIMARY KEY (account_id, id)
);`);
    const names = columns.filter(([c]) => c !== 'id').map(([c]) => c);
    out.push(`INSERT OR REPLACE INTO ${name} (account_id, id, ${names.join(', ')})
SELECT account_id, row_id, ${names
      .map((c) => `json_extract(data, '$.${c}')`)
      .join(', ')}
FROM sync_rows WHERE tbl = '${name}' AND deleted = 0;`);
  }
  console.log(out.join('\n\n'));
} else {
  const map = Object.fromEntries(
    tables.map(({ name, columns }) => [name, columns.map(([c]) => c)]),
  );
  writeFileSync(
    join(here, '../src/mirror_tables.js'),
    `// Generated by scripts/mirror-tables.mjs from lib/core/db/tables.dart.
// Columns of the cloud copy of each synced app table (besides account_id).
export const MIRROR_TABLES = ${JSON.stringify(map, null, 2)};
`,
  );
  console.log(`${tables.length} tables`);
}
